template <typename T>
std::unique_ptr<T> parse_from_bytes(const unsigned char* bytes, std::size_t size) {
    std::string payload(reinterpret_cast<const char*>(bytes), size);
    std::stringstream ss(payload, std::ios::in | std::ios::out | std::ios::binary);
    kaitai::kstream ks(&ss);
    return std::unique_ptr<T>(new T(&ks));
}

