BOOST_AUTO_TEST_CASE(test_mpc60seq_v2_probe_reads_real_seq01_bytes) {
    auto parsed = parse_from_bytes<mpc60seq_v2_probe_t>(kMpc60V214Seq01, sizeof(kMpc60V214Seq01));

    BOOST_CHECK_EQUAL(parsed->file_id(), std::string("\x03", 1));
    BOOST_CHECK_EQUAL(parsed->file_format_version(), std::string("\x02", 1));
    BOOST_CHECK_EQUAL(parsed->sequence_header()->sequence_name(), std::string("SEQ01", 5) + std::string(11, ' '));
    BOOST_CHECK_EQUAL(parsed->sequence_header()->number_of_bars(), 2);
    BOOST_CHECK_EQUAL(parsed->sequence_header()->tempo(), 1200);
    BOOST_CHECK_EQUAL(parsed->sequence_header()->number_of_tempo_changes(), 1);
    BOOST_CHECK_EQUAL(parsed->sequence_header()->number_of_active_track_headers(), 3);
    BOOST_REQUIRE_EQUAL(parsed->track_headers()->size(), 3U);
    BOOST_CHECK_EQUAL(parsed->track_headers()->at(0)->track_name(), std::string("TRK01", 5) + std::string(11, ' '));
    BOOST_CHECK_EQUAL(parsed->track_headers()->at(0)->track_volume(), 100);
    BOOST_CHECK_EQUAL(parsed->track_headers()->at(1)->absolute_recorded_track_number(), -1);
    BOOST_CHECK_EQUAL(parsed->track_headers()->at(2)->absolute_recorded_track_number(), -1);
    BOOST_REQUIRE_EQUAL(parsed->tempo_changes()->size(), 1U);
    BOOST_REQUIRE_EQUAL(parsed->events()->size(), 5U);
    BOOST_CHECK_EQUAL(parsed->events()->at(0)->status(), 0xA8);
    BOOST_CHECK_EQUAL(parsed->events()->at(1)->status(), 0x98);
    BOOST_CHECK_EQUAL(parsed->events()->at(2)->status(), 0x88);
    BOOST_CHECK_EQUAL(parsed->events()->at(3)->status(), 0xA8);
    BOOST_CHECK_EQUAL(parsed->events()->at(4)->status(), 0x88);
    BOOST_CHECK_EQUAL(parsed->events()->at(1)->track_number(), 1);
    auto* note = dynamic_cast<mpc60seq_v2_probe_t::note_event_t*>(parsed->events()->at(1)->event_body());
    BOOST_REQUIRE(note != nullptr);
    BOOST_CHECK_EQUAL(note->note_number(), 1);
    BOOST_CHECK_EQUAL(note->velocity(), 64);
}

BOOST_AUTO_TEST_CASE(test_mpc60all_v2_probe_reads_real_all_bytes) {
    auto parsed = parse_from_bytes<mpc60all_v2_probe_t>(kMpc60V214AllSeqs, sizeof(kMpc60V214AllSeqs));

    BOOST_CHECK_EQUAL(parsed->file_id(), std::string("\x04", 1));
    BOOST_CHECK_EQUAL(parsed->file_format_version(), std::string("\x02", 1));
    BOOST_CHECK_EQUAL(parsed->total_number_of_bytes_in_all_sequences(), 305U);
    BOOST_REQUIRE_EQUAL(parsed->sequence_bodies().size(), 305U);
    BOOST_CHECK_EQUAL(static_cast<unsigned char>(parsed->sequence_bodies().at(0)), 0x01);
    BOOST_CHECK_EQUAL(static_cast<unsigned char>(parsed->sequence_bodies().at(1)), 0x18);
    BOOST_CHECK_EQUAL(static_cast<unsigned char>(parsed->sequence_bodies().at(7)), 'S');
    BOOST_CHECK_EQUAL(static_cast<unsigned char>(parsed->sequence_bodies().back()), 0xFF);
    BOOST_REQUIRE_EQUAL(parsed->songs()->size(), 1U);
    BOOST_CHECK_EQUAL(parsed->songs()->at(0)->step_count(), 0);
}

